#!/usr/bin/env node
/* Builds rules/srd5-spells.js from the 5e-bits/5e-database SRD 5.1 spell list.

   Source: https://github.com/5e-bits/5e-database — src/2014/en/5e-SRD-Spells.json
   (dataset under the MIT licence; the spell text itself is SRD 5.1, CC-BY-4.0).

   Usage:
     curl -o spells.json https://raw.githubusercontent.com/5e-bits/5e-database/main/src/2014/en/5e-SRD-Spells.json
     node tools/build-srd5-spells.js spells.json

   Writes rules/srd5-spells.js. Run it again to regenerate; do not edit the output by hand. */
'use strict';

const fs = require('fs');
const path = require('path');

const input = process.argv[2];
if (!input) {
  console.error('Usage: node tools/build-srd5-spells.js <5e-SRD-Spells.json>');
  process.exit(1);
}

const raw = JSON.parse(fs.readFileSync(input, 'utf8'));

// Class ids in rules/srd5.js are the same lowercase words the source uses.
const CLASSES = ['bard', 'cleric', 'druid', 'paladin', 'ranger', 'sorcerer', 'warlock', 'wizard'];

// The source lowercases ability names ("a dexterity saving throw"); the SRD capitalises them.
const ABILITY_RE = /\b(strength|dexterity|constitution|intelligence|wisdom|charisma)\b(?=\s+(saving throw|check|modifier|score|\(|save))/g;
const fixText = (s) => String(s).replace(ABILITY_RE, (m) => m[0].toUpperCase() + m.slice(1));

const idOf = (name) => name.toLowerCase().replace(/['’]/g, '').replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '');

const spells = raw.map((s) => {
  const out = {
    id: idOf(s.name),
    name: s.name,
    level: s.level,
    school: s.school.name,
    castingTime: s.casting_time,
    ritual: !!s.ritual,
    range: s.range,
    components: s.components.slice(),
    material: s.material || null,
    duration: s.duration,
    concentration: !!s.concentration,
    classes: s.classes.map((c) => c.index).filter((c) => CLASSES.includes(c)).sort(),
    desc: s.desc.map(fixText).filter((p) => p.trim()),
    higherLevel: (s.higher_level || []).map(fixText).filter((p) => p.trim()),
    ruleset: '2014',
    source: 'SRD',
    license: 'srd51'
  };
  if (s.attack_type) out.attack = s.attack_type;
  if (s.dc) out.save = s.dc.dc_type.index;
  if (s.area_of_effect) out.area = { type: s.area_of_effect.type, size: s.area_of_effect.size };
  // damage is an object on some spells and an array on others.
  const types = [].concat(s.damage || []).map((d) => d && d.damage_type && d.damage_type.name).filter(Boolean);
  if (types.length) out.damageType = [...new Set(types)].join(', ');
  return out;
}).sort((a, b) => a.level - b.level || a.name.localeCompare(b.name));

// Sanity checks: fail loudly instead of writing bad data.
const ids = new Set();
for (const s of spells) {
  if (ids.has(s.id)) throw new Error('Duplicate id ' + s.id);
  ids.add(s.id);
  if (!(s.level >= 0 && s.level <= 9)) throw new Error('Bad level on ' + s.name);
  if (!s.classes.length) throw new Error('No class list on ' + s.name);
  if (!s.desc.length) throw new Error('No description on ' + s.name);
}
if (spells.length !== 319) throw new Error('Expected the 319 SRD 5.1 spells, got ' + spells.length);

const header = `/* ========================================================
   D&D 5e (2014) SPELLS — SRD 5.1 content only (319 spells)
   GENERATED by tools/build-srd5-spells.js. Do not edit by hand.

   This work includes material taken from the System Reference
   Document 5.1 ("SRD 5.1") by Wizards of the Coast LLC and
   available at https://dnd.wizards.com/resources/systems-reference-document.
   The SRD 5.1 is licensed under the Creative Commons Attribution
   4.0 International License available at
   https://creativecommons.org/licenses/by/4.0/legalcode.

   Converted from the 5e-bits/5e-database dataset
   (https://github.com/5e-bits/5e-database), MIT licence,
   Copyright (c) 2018-2020 Adrian Padua, Christopher Ward.

   Fields: id, name, level (0 = cantrip), school, castingTime,
   ritual, range, components (V/S/M), material, duration,
   concentration (duration then reads "Concentration, up to …"),
   classes (class ids from rules/srd5.js), desc and higherLevel
   (paragraphs; a few hold Markdown tables), ruleset, source,
   license, and where they apply: attack, save, area, damageType.
   ======================================================== */
`;

const body = `(function (root) {
  'use strict';
  const SPELLS_SRD5 = ${JSON.stringify(spells, null, 1)};

  if (typeof module !== 'undefined' && module.exports) module.exports = SPELLS_SRD5;
  else root.SPELLS_SRD5 = SPELLS_SRD5;
})(typeof window !== 'undefined' ? window : this);
`;

const outPath = path.join(__dirname, '..', 'rules', 'srd5-spells.js');
fs.writeFileSync(outPath, header + body);
console.log('Wrote ' + spells.length + ' spells to ' + path.relative(process.cwd(), outPath));
